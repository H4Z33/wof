// Command protoc-gen-gdscript is a protoc/buf plugin that generates GDScript
// (Godot 4) message classes with protobuf wire encoding.
//
// Supported subset (enough for the game protocol, fails loudly otherwise):
//   - proto3 scalars, enums, messages, repeated fields (packed and unpacked)
//   - oneofs whose members are all message types
//   - messages and enums from the same file only
//
// Not supported: maps, proto3 `optional`, groups, cross-file type references.
//
// Each .proto produces one <name>.pb.gd file with a self-contained wire
// runtime, so the client needs no addon. Usage from GDScript:
//
//	const PB = preload("res://gen/convergence/v1/world.pb.gd")
//	var msg := PB.ClientMessage.new()
package main

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			if err := generateFile(gen, f); err != nil {
				return fmt.Errorf("%s: %w", f.Desc.Path(), err)
			}
		}
		return nil
	})
}

// gdKeywords are GDScript reserved words and names that clash with Object
// members; fields with these names get a trailing underscore.
var gdKeywords = map[string]bool{
	"if": true, "elif": true, "else": true, "for": true, "while": true, "match": true,
	"break": true, "continue": true, "pass": true, "return": true, "class": true,
	"class_name": true, "extends": true, "is": true, "in": true, "as": true, "self": true,
	"signal": true, "func": true, "static": true, "const": true, "enum": true, "var": true,
	"breakpoint": true, "preload": true, "await": true, "yield": true, "assert": true,
	"void": true, "and": true, "or": true, "not": true, "true": true, "false": true,
	"null": true, "super": true, "free": true, "get": true, "set": true, "call": true,
	"connect": true, "notification": true, "to_string": true, "get_class": true,
}

func fieldName(f *protogen.Field) string {
	n := string(f.Desc.Name())
	if gdKeywords[n] {
		return n + "_"
	}
	return n
}

// gdGlobalTypes are Godot global classes and enums that a generated inner
// class must not shadow; such types get a trailing underscore.
var gdGlobalTypes = map[string]bool{
	"Error": true, "Object": true, "Node": true, "Resource": true, "RefCounted": true,
	"String": true, "StringName": true, "NodePath": true, "Array": true, "Dictionary": true,
	"Vector2": true, "Vector2i": true, "Vector3": true, "Vector3i": true, "Vector4": true,
	"Color": true, "Rect2": true, "Transform2D": true, "Transform3D": true, "Basis": true,
	"Quaternion": true, "Plane": true, "AABB": true, "Projection": true, "Callable": true,
	"Signal": true, "RID": true, "Time": true, "OS": true, "Engine": true, "Input": true,
	"JSON": true, "Image": true, "Texture": true, "Mesh": true, "Material": true,
	"Animation": true, "Timer": true, "Label": true, "Button": true, "Camera3D": true,
	"Key": true, "MouseButton": true, "Side": true, "Corner": true, "Orientation": true,
	"Variant": true, "PropertyHint": true, "JoyButton": true, "JoyAxis": true,
}

// typeName flattens nested names: Outer.Inner -> Outer_Inner.
func typeName(full protoreflect.FullName, pkg protoreflect.FullName) string {
	s := strings.ReplaceAll(strings.TrimPrefix(string(full), string(pkg)+"."), ".", "_")
	if gdGlobalTypes[s] {
		return s + "_"
	}
	return s
}

type generator struct {
	g   *protogen.GeneratedFile
	pkg protoreflect.FullName
	src string
}

func generateFile(gen *protogen.Plugin, f *protogen.File) error {
	gr := &generator{
		// Mirror the .proto path (GeneratedFilenamePrefix follows go_package).
		g:   gen.NewGeneratedFile(strings.TrimSuffix(f.Desc.Path(), ".proto")+".pb.gd", ""),
		pkg: f.Desc.Package(),
		src: f.Desc.Path(),
	}
	gr.p("# Code generated by protoc-gen-gdscript. DO NOT EDIT.")
	gr.p("# source: ", f.Desc.Path())
	gr.p("extends RefCounted")
	gr.p()
	gr.g.P(wireRuntime)

	var enums []*protogen.Enum
	var msgs []*protogen.Message
	enums = append(enums, f.Enums...)
	var walk func(ms []*protogen.Message)
	walk = func(ms []*protogen.Message) {
		for _, m := range ms {
			if m.Desc.IsMapEntry() {
				continue
			}
			msgs = append(msgs, m)
			enums = append(enums, m.Enums...)
			walk(m.Messages)
		}
	}
	walk(f.Messages)

	for _, e := range enums {
		gr.genEnum(e)
	}
	for _, m := range msgs {
		if err := gr.genMessage(m); err != nil {
			return fmt.Errorf("message %s: %w", m.Desc.FullName(), err)
		}
	}
	return nil
}

func (gr *generator) p(v ...any) { gr.g.P(v...) }

func (gr *generator) genEnum(e *protogen.Enum) {
	gr.p("enum ", typeName(e.Desc.FullName(), gr.pkg), " {")
	for _, v := range e.Values {
		gr.p("\t", v.Desc.Name(), " = ", v.Desc.Number(), ",")
	}
	gr.p("}")
	gr.p()
}

// scalar describes how one proto kind maps to GDScript.
type scalar struct {
	gdType   string
	zero     string
	wireType int
	write    string // _Writer method
	read     string // _Reader method
	packable bool
}

var scalars = map[protoreflect.Kind]scalar{
	protoreflect.BoolKind:     {"bool", "false", 0, "boolean", "boolean", true},
	protoreflect.EnumKind:     {"int", "0", 0, "varint", "varint", true},
	protoreflect.Int32Kind:    {"int", "0", 0, "varint", "int32", true},
	protoreflect.Int64Kind:    {"int", "0", 0, "varint", "varint", true},
	protoreflect.Uint32Kind:   {"int", "0", 0, "varint", "uint32", true},
	protoreflect.Uint64Kind:   {"int", "0", 0, "varint", "varint", true},
	protoreflect.Sint32Kind:   {"int", "0", 0, "zigzag", "zigzag32", true},
	protoreflect.Sint64Kind:   {"int", "0", 0, "zigzag", "zigzag", true},
	protoreflect.Fixed32Kind:  {"int", "0", 5, "fixed32", "fixed32", true},
	protoreflect.Sfixed32Kind: {"int", "0", 5, "fixed32", "sfixed32", true},
	protoreflect.Fixed64Kind:  {"int", "0", 1, "fixed64", "fixed64", true},
	protoreflect.Sfixed64Kind: {"int", "0", 1, "fixed64", "fixed64", true},
	protoreflect.FloatKind:    {"float", "0.0", 5, "f32", "f32", true},
	protoreflect.DoubleKind:   {"float", "0.0", 1, "f64", "f64", true},
	protoreflect.StringKind:   {"String", `""`, 2, "string", "string", false},
	protoreflect.BytesKind:    {"PackedByteArray", "PackedByteArray()", 2, "bytes", "bytes", false},
}

func (gr *generator) checkField(m *protogen.Message, f *protogen.Field) error {
	d := f.Desc
	switch {
	case d.IsMap():
		return fmt.Errorf("field %s: maps are not supported", d.Name())
	case d.HasOptionalKeyword():
		return fmt.Errorf("field %s: proto3 optional is not supported", d.Name())
	case d.Kind() == protoreflect.GroupKind:
		return fmt.Errorf("field %s: groups are not supported", d.Name())
	case f.Oneof != nil && d.Kind() != protoreflect.MessageKind:
		return fmt.Errorf("field %s: oneof members must be messages", d.Name())
	}
	if f.Message != nil && f.Message.Desc.ParentFile().Path() != gr.src {
		return fmt.Errorf("field %s: type %s is from another file", d.Name(), f.Message.Desc.FullName())
	}
	if f.Enum != nil && f.Enum.Desc.ParentFile().Path() != gr.src {
		return fmt.Errorf("field %s: enum %s is from another file", d.Name(), f.Enum.Desc.FullName())
	}
	return nil
}

func (gr *generator) genMessage(m *protogen.Message) error {
	name := typeName(m.Desc.FullName(), gr.pkg)
	for _, f := range m.Fields {
		if err := gr.checkField(m, f); err != nil {
			return err
		}
	}

	gr.p("class ", name, ":")
	gr.p("\textends RefCounted")
	if len(m.Fields) == 0 {
		gr.p()
	}

	// Fields.
	for _, f := range m.Fields {
		n := fieldName(f)
		d := f.Desc
		switch {
		case d.Kind() == protoreflect.MessageKind && d.IsList():
			gr.p("\tvar ", n, ": Array[", typeName(f.Message.Desc.FullName(), gr.pkg), "] = []")
		case d.Kind() == protoreflect.MessageKind:
			gr.p("\tvar ", n, ": ", typeName(f.Message.Desc.FullName(), gr.pkg), " = null")
		case d.IsList():
			gr.p("\tvar ", n, ": Array[", scalars[d.Kind()].gdType, "] = []")
		default:
			s := scalars[d.Kind()]
			gr.p("\tvar ", n, ": ", s.gdType, " = ", s.zero)
		}
	}
	gr.p()

	// Oneof helpers: which_<oneof>() returns the set member's field name.
	for _, o := range m.Oneofs {
		if o.Desc.IsSynthetic() {
			continue
		}
		gr.p("\tfunc which_", o.Desc.Name(), "() -> String:")
		for _, f := range o.Fields {
			gr.p("\t\tif ", fieldName(f), " != null: return \"", fieldName(f), "\"")
		}
		gr.p("\t\treturn \"\"")
		gr.p()
	}

	// Encoder.
	gr.p("\tfunc _write(w: _Writer) -> void:")
	if len(m.Fields) == 0 {
		gr.p("\t\tpass")
	}
	for _, f := range m.Fields {
		gr.genWriteField(f)
	}
	gr.p()

	// Decoder.
	gr.p("\tfunc _read(r: _Reader) -> void:")
	gr.p("\t\twhile not r.at_end():")
	gr.p("\t\t\tvar tag := r.varint()")
	gr.p("\t\t\tvar wt := tag & 7")
	gr.p("\t\t\tmatch tag >> 3:")
	for _, f := range m.Fields {
		gr.genReadField(f)
	}
	gr.p("\t\t\t\t_:")
	gr.p("\t\t\t\t\tr.skip(wt)")
	gr.p()

	gr.p("\tfunc to_bytes() -> PackedByteArray:")
	gr.p("\t\tvar w := _Writer.new()")
	gr.p("\t\t_write(w)")
	gr.p("\t\treturn w.buf")
	gr.p()
	gr.p("\t# Returns null if the bytes are malformed.")
	gr.p("\tstatic func from_bytes(b: PackedByteArray) -> ", name, ":")
	gr.p("\t\tvar m := ", name, ".new()")
	gr.p("\t\tvar r := _Reader.new(b, 0, b.size())")
	gr.p("\t\tm._read(r)")
	gr.p("\t\treturn null if r.failed else m")
	gr.p()
	return nil
}

func (gr *generator) genWriteField(f *protogen.Field) {
	n := fieldName(f)
	d := f.Desc
	num := d.Number()
	switch {
	case d.Kind() == protoreflect.MessageKind && d.IsList():
		gr.p("\t\tfor v in ", n, ":")
		gr.p("\t\t\tw.message(", num, ", v)")
	case d.Kind() == protoreflect.MessageKind:
		gr.p("\t\tif ", n, " != null:")
		gr.p("\t\t\tw.message(", num, ", ", n, ")")
	case d.IsList():
		s := scalars[d.Kind()]
		if s.packable {
			gr.p("\t\tif not ", n, ".is_empty():")
			gr.p("\t\t\tvar pw := _Writer.new()")
			gr.p("\t\t\tfor v in ", n, ":")
			gr.p("\t\t\t\tpw.", s.write, "(v)")
			gr.p("\t\t\tw.tag(", num, ", 2)")
			gr.p("\t\t\tw.varint(pw.buf.size())")
			gr.p("\t\t\tw.buf.append_array(pw.buf)")
		} else {
			gr.p("\t\tfor v in ", n, ":")
			gr.p("\t\t\tw.tag(", num, ", ", s.wireType, ")")
			gr.p("\t\t\tw.", s.write, "(v)")
		}
	default:
		s := scalars[d.Kind()]
		cond := n + " != " + s.zero
		if d.Kind() == protoreflect.StringKind || d.Kind() == protoreflect.BytesKind {
			cond = "not " + n + ".is_empty()"
		}
		gr.p("\t\tif ", cond, ":")
		gr.p("\t\t\tw.tag(", num, ", ", s.wireType, ")")
		gr.p("\t\t\tw.", s.write, "(", n, ")")
	}
}

func (gr *generator) genReadField(f *protogen.Field) {
	n := fieldName(f)
	d := f.Desc
	gr.p("\t\t\t\t", d.Number(), ":")
	switch {
	case d.Kind() == protoreflect.MessageKind:
		t := typeName(f.Message.Desc.FullName(), gr.pkg)
		gr.p("\t\t\t\t\tif wt != 2:")
		gr.p("\t\t\t\t\t\tr.skip(wt)")
		gr.p("\t\t\t\t\telse:")
		gr.p("\t\t\t\t\t\tvar sub := r.sub()")
		gr.p("\t\t\t\t\t\tvar v := ", t, ".new()")
		gr.p("\t\t\t\t\t\tv._read(sub)")
		gr.p("\t\t\t\t\t\tif sub.failed: r.failed = true")
		if d.IsList() {
			gr.p("\t\t\t\t\t\t", n, ".append(v)")
		} else {
			// Setting one oneof member clears the others (last one wins).
			if f.Oneof != nil {
				for _, other := range f.Oneof.Fields {
					if other != f {
						gr.p("\t\t\t\t\t\t", fieldName(other), " = null")
					}
				}
			}
			gr.p("\t\t\t\t\t\t", n, " = v")
		}
	case d.IsList():
		s := scalars[d.Kind()]
		if s.packable {
			gr.p("\t\t\t\t\tif wt == 2:")
			gr.p("\t\t\t\t\t\tvar sub := r.sub()")
			gr.p("\t\t\t\t\t\twhile not sub.at_end(): ", n, ".append(sub.", s.read, "())")
			gr.p("\t\t\t\t\t\tif sub.failed: r.failed = true")
			gr.p("\t\t\t\t\telif wt == ", s.wireType, ": ", n, ".append(r.", s.read, "())")
			gr.p("\t\t\t\t\telse: r.skip(wt)")
		} else {
			gr.p("\t\t\t\t\tif wt == ", s.wireType, ": ", n, ".append(r.", s.read, "())")
			gr.p("\t\t\t\t\telse: r.skip(wt)")
		}
	default:
		s := scalars[d.Kind()]
		gr.p("\t\t\t\t\tif wt == ", s.wireType, ": ", n, " = r.", s.read, "()")
		gr.p("\t\t\t\t\telse: r.skip(wt)")
	}
}

// wireRuntime is emitted at the top of every generated file. GDScript ints are
// signed 64-bit, which matches protobuf's 64-bit varint arithmetic.
const wireRuntime = `class _Writer:
	extends RefCounted
	const _MASK57 := 0x01FFFFFFFFFFFFFF  # clears sign-extension after >> 7
	var buf := PackedByteArray()

	func tag(field: int, wire_type: int) -> void:
		varint((field << 3) | wire_type)

	func varint(v: int) -> void:
		while true:
			var b := v & 0x7F
			v = (v >> 7) & _MASK57
			if v == 0:
				buf.append(b)
				return
			buf.append(b | 0x80)

	func boolean(v: bool) -> void:
		buf.append(1 if v else 0)

	func zigzag(v: int) -> void:
		varint((v << 1) ^ (v >> 63))

	func fixed32(v: int) -> void:
		var o := buf.size()
		buf.resize(o + 4)
		buf.encode_u32(o, v & 0xFFFFFFFF)

	func fixed64(v: int) -> void:
		var o := buf.size()
		buf.resize(o + 8)
		buf.encode_s64(o, v)

	func f32(v: float) -> void:
		var o := buf.size()
		buf.resize(o + 4)
		buf.encode_float(o, v)

	func f64(v: float) -> void:
		var o := buf.size()
		buf.resize(o + 8)
		buf.encode_double(o, v)

	func string(v: String) -> void:
		bytes(v.to_utf8_buffer())

	func bytes(v: PackedByteArray) -> void:
		varint(v.size())
		buf.append_array(v)

	func message(field: int, m) -> void:
		var w := _Writer.new()
		m._write(w)
		tag(field, 2)
		varint(w.buf.size())
		buf.append_array(w.buf)


class _Reader:
	extends RefCounted
	const _MASK63 := 0x7FFFFFFFFFFFFFFF  # clears sign-extension after >> 1
	var buf: PackedByteArray
	var pos: int
	var end: int
	var failed := false

	func _init(b: PackedByteArray, start: int, stop: int) -> void:
		buf = b
		pos = start
		end = stop

	func at_end() -> bool:
		return failed or pos >= end

	func _need(n: int) -> bool:
		if pos + n > end:
			failed = true
			pos = end
			return false
		return true

	func varint() -> int:
		var result := 0
		var shift := 0
		while shift < 64:
			if not _need(1):
				return 0
			var b := buf[pos]
			pos += 1
			result |= (b & 0x7F) << shift
			if b & 0x80 == 0:
				return result
			shift += 7
		failed = true
		return 0

	func int32() -> int:
		var v := varint() & 0xFFFFFFFF
		return v - 0x100000000 if v >= 0x80000000 else v

	func uint32() -> int:
		return varint() & 0xFFFFFFFF

	func boolean() -> bool:
		return varint() != 0

	func zigzag() -> int:
		var v := varint()
		return ((v >> 1) & _MASK63) ^ -(v & 1)

	func zigzag32() -> int:
		var v := varint() & 0xFFFFFFFF
		return ((v >> 1) & _MASK63) ^ -(v & 1)

	func fixed32() -> int:
		if not _need(4):
			return 0
		var v := buf.decode_u32(pos)
		pos += 4
		return v

	func sfixed32() -> int:
		if not _need(4):
			return 0
		var v := buf.decode_s32(pos)
		pos += 4
		return v

	func fixed64() -> int:
		if not _need(8):
			return 0
		var v := buf.decode_s64(pos)
		pos += 8
		return v

	func f32() -> float:
		if not _need(4):
			return 0.0
		var v := buf.decode_float(pos)
		pos += 4
		return v

	func f64() -> float:
		if not _need(8):
			return 0.0
		var v := buf.decode_double(pos)
		pos += 8
		return v

	func bytes() -> PackedByteArray:
		var n := varint()
		if n < 0 or not _need(n):
			return PackedByteArray()
		var v := buf.slice(pos, pos + n)
		pos += n
		return v

	func string() -> String:
		return bytes().get_string_from_utf8()

	# Reader over the next length-delimited field; advances past it.
	func sub() -> _Reader:
		var n := varint()
		if n < 0 or not _need(n):
			return _Reader.new(buf, end, end)
		var r := _Reader.new(buf, pos, pos + n)
		pos += n
		return r

	func skip(wire_type: int) -> void:
		var n := 0
		match wire_type:
			0:
				varint()
				return
			1:
				n = 8
			2:
				n = varint()
			5:
				n = 4
			_:
				failed = true
				return
		if n >= 0 and _need(n):
			pos += n
`
